bool grace_is_boss(uint32_t flag_id) {
	return array_contains(BOSS_GRACES, ARRAY_COUNT(BOSS_GRACES), flag_id);
}

bool grace_is_ashen_capital(uint32_t flag_id) {
	return array_contains(ASHEN_CAPITAL_GRACES, ARRAY_COUNT(ASHEN_CAPITAL_GRACES), flag_id);
}